//! 桌面語言只投影既有 visual.language；翻譯展示文案，不翻譯持久化值或使用者內容。
use gpui_kit::{App, Global};
use veyra_core::domain::DesktopLanguage;
#[derive(Default)]
pub struct Locale(pub DesktopLanguage);
impl Global for Locale {}
pub fn set(language: DesktopLanguage, cx: &mut App) {
    if cx.global::<Locale>().0 != language {
        cx.set_global(Locale(language));
        // 所有保留的頁面、浮層與元件都必須在切換後重新繪製。
        cx.refresh_windows();
    }
}
pub fn tr<'a>(cx: &App, key: &'a str) -> &'a str {
    translate(cx.global::<Locale>().0, key)
}
pub fn translate(language: DesktopLanguage, key: &str) -> &str {
    let Some(row) = MESSAGES.iter().find(|row| row[0] == key) else {
        return key;
    };
    row[match language {
        DesktopLanguage::SimplifiedChinese => 0,
        DesktopLanguage::English => 1,
        DesktopLanguage::TraditionalChinese => 2,
    }]
}
/// 通知保留原始訊息，到 render 才翻譯，因此開著的通知也會跟隨語言。
pub fn message(cx: &App, text: &str) -> String {
    let translated = tr(cx, text);
    translated
        .split(" · ")
        .map(|part| tr(cx, part))
        .collect::<Vec<_>>()
        .join(" · ")
}
/// 图库的名称/变体也是 UI 文案；用户填写的站点名称不经过此函数。
pub fn icon_label(language: DesktopLanguage, label: &str) -> String {
    let mut out = String::new();
    let mut start = 0;
    for (i, c) in label.char_indices() {
        if matches!(c, '(' | ')' | '（' | '）') {
            out.push_str(translate(language, &label[start..i]));
            out.push(c);
            start = i + c.len_utf8();
        }
    }
    out.push_str(translate(language, &label[start..]));
    out
}
